-- Derived from the Election Commission BLO list as on 27.07.2026:
-- 80,710 polling-station Parts across all 294 assembly constituencies.
--
-- PRIVACY -- READ BEFORE EXTENDING
-- The source list also carries each Booth Level Officer's name, mobile
-- number, designation and department. Those four columns are DELIBERATELY
-- NOT LOADED. What is here is only the public geography of a polling
-- station: constituency, part number, building. anon has SELECT on both
-- tables below, so adding BLO contact details here would publish the
-- personal mobile numbers of ~80,000 government employees.
--
-- District names are normalised to the 23 options in the site's district
-- dropdown. The BLO list uses 24 -- it splits KOLKATA NORTH / KOLKATA SOUTH,
-- which both fold to 'Kolkata' here. If you ever change the dropdown in
-- volunteer/index.html, this mapping has to change with it, or the
-- constituency filter silently returns nothing.
-- ---------------------------------------------------------------------------

